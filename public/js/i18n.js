  Object.keys(V3_UI_PATCH).forEach(function (code) {
    if (UI_STRINGS[code]) {
      Object.assign(UI_STRINGS[code], V3_UI_PATCH[code]);
    }
  });

  function resolveLanguage(rawCode) {
    if (!rawCode || typeof rawCode !== 'string') return 'en';
    var cleaned = rawCode.trim().toLowerCase().replace('_', '-');
    if (LANGUAGE_ALIASES[cleaned]) return LANGUAGE_ALIASES[cleaned];
    var prefix = cleaned.split('-')[0];
    if (LANGUAGE_ALIASES[prefix]) return LANGUAGE_ALIASES[prefix];
    return 'en';
  }

  function getInitialLanguage() {
    if (typeof window !== 'undefined' && window.location) {
      var params = new URLSearchParams(window.location.search || '');
      var urlLang = params.get('lang');
      if (urlLang) {
        return resolveLanguage(urlLang);
      }
    }
    if (typeof window !== 'undefined' && window.localStorage) {
      try {
        var saved = window.localStorage.getItem(LANG_STORAGE_KEY);
        if (saved) return resolveLanguage(saved);
      } catch (_e) {
        // Ignore storage errors
      }
    }
    if (typeof navigator !== 'undefined' && navigator.language) {
      return resolveLanguage(navigator.language);
    }
    return 'en';
  }

  function saveLanguage(langCode) {
    var resolved = resolveLanguage(langCode);
    if (typeof window !== 'undefined' && window.localStorage) {
      try {
        window.localStorage.setItem(LANG_STORAGE_KEY, resolved);
      } catch (_e) {
        // Ignore storage errors
      }
    }
    return resolved;
  }

  function getLanguageMeta(langCode) {
    var resolved = resolveLanguage(langCode);
    for (var i = 0; i < SUPPORTED_LANGUAGES.length; i++) {
      if (SUPPORTED_LANGUAGES[i].code === resolved) {
        return SUPPORTED_LANGUAGES[i];
      }
    }
    return SUPPORTED_LANGUAGES[0];
  }

  function getStrings(langCode) {
    var resolved = resolveLanguage(langCode);
    return UI_STRINGS[resolved] || UI_STRINGS.en;
  }

  function buildCardNarrationText(langCode, cardData) {
    var strings = getStrings(langCode);
    var parts = [strings.narrationPrefix];
    if (cardData && cardData.title) parts.push(String(cardData.title) + '.');
    if (cardData && cardData.subtitle) parts.push(String(cardData.subtitle) + '.');
    if (cardData && cardData.summary) parts.push(String(cardData.summary));
    if (cardData && Array.isArray(cardData.notes) && cardData.notes.length > 0) {
      parts.push(strings.explorerNotes.replace(/^[^\w\u00C0-\uFFFF]+/, '') + ': ' + cardData.notes.join(' '));
    }
    return parts.join(' ');
  }

  var api = {
    LANG_STORAGE_KEY: LANG_STORAGE_KEY,
    SUPPORTED_LANGUAGES: SUPPORTED_LANGUAGES,
    UI_STRINGS: UI_STRINGS,
    resolveLanguage: resolveLanguage,
    getInitialLanguage: getInitialLanguage,
    saveLanguage: saveLanguage,
    getLanguageMeta: getLanguageMeta,
    getStrings: getStrings,
    buildCardNarrationText: buildCardNarrationText
  };

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = api;
  }
  root.OnePieceI18n = api;
